// Writes data/review/AUDIT_LOG.md — the clean-up trail (parser fixes + per-resume corrections/notes/warnings).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { evaluate } from '../lib/engine/score.js';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { profiles } = JSON.parse(fs.readFileSync(path.join(ROOT, 'public/data/profiles.json'), 'utf8'));
const auto = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/review/auto_extraction.json'), 'utf8'));
const autoById = Object.fromEntries(auto.map((p) => [p.id, p]));

let md = `# Data clean-up audit log

Generated by \`npm run audit\` from \`public/data/profiles.json\` (final) and \`data/review/auto_extraction.json\` (raw parser output, before reviewer corrections).

## 1. How the review was done
1. Ran the automatic extractor on all 47 resumes and dumped every record in compact form (\`node scripts/dump.mjs\`).
2. Read each source resume next to its record and checked headline, every experience entry (role / company / dates / months), education rows, projects, skills and the claimed years.
3. **Generalisable bugs were fixed in the parser** (so uploads benefit too). **Record-specific problems were fixed in \`data/review/overrides.json\`** with a written reason. Context that changes no data became a reviewer note.
4. Spot-checked scored evidence (\`node scripts/explain.mjs <ID> lca|uiux\`) for false-positive keyword matches and tightened the rubric patterns.

## 2. Parser fixes found during review (apply to all resumes and uploads)
| Problem seen | Example | Fix |
|---|---|---|
| Role/company split on the first em dash | VM: "Senior Consultant — Energy Efficiency & Sustainability — TA Europe GmbH" put the company in the role | Company = last " — " segment |
| University line read as a degree because it starts with "MS" | TM: "MS Ramaiah University…" became a second master's degree | A degree-start pattern decides new rows; institution keywords win otherwise |
| Numeric month/year left inside institution names | MS: "Technical University of Chemnitz, 10/2021 – 03/2025" | Strip MM/YYYY ranges into the years field |
| Hyphen normaliser joined dates to words | "December 2025 - January 2026" → "2025-January" | Only collapse " - " between lower-case words ("cradle - to - gate") |
| Plural forms missed | VG: "conducted Life Cycle Assessments" not detected → wrongly "no hands-on LCA" | LCA vocabulary accepts plurals (assessments, analyses, inventories) |
| Keyword false positives | "emission inventory" → LCI; "building strong foundations" → construction; "GHG accounting" → finance; "research paper" → benchmarking | Patterns tightened in \`lib/engine/rubrics.js\` |
| Graphic-design jobs counted as full UX tenure | AL: freelance graphic designer since 2021 counted as 5.2 yrs of UX | Titles that are graphic/visual/front-end only count at half weight (UI/UX rubric) |

## 3. Dataset-level issues
- **1 unreadable file**: \`anonymized_resume_1793685080327.docx\` contains no text. It is kept in the pile as *Uncertain* with an explicit error, not dropped.
- **Anonymisation artefacts**: ISO standard numbers are stripped throughout ("ISO /s", "ISO :2006"), as are some numbers and words ("over 2.s", "Scope s", "Led ion", "40-omers"). The parser detects and flags these. LCA-context "ISO /" is accepted as ISO 14040/44 evidence, and redacted years claims are ignored, not guessed.
- **Date formats**: 10+ variants (\`MM/YYYY\`, \`Sep '25\`, \`Jan 26\`, \`Jan – April 2026\`, year-only, \`8 Months\`, \`Ongoing\`, \`null\`, \`Not specified\`, \`Dates not provided\`, future end dates). All are parsed or flagged; "Present" resolves to a fixed snapshot (Nov 2026).
- **JD inconsistency**: the brief says the LCA role needs 4–6 yrs, but JD1 says 2–3 yrs. The default ranking uses the JD text; the UI has a toggle to rank against the brief instead.

## 4. Per-resume log
`;
for (const p of profiles) {
  const r = evaluate(p, { lcaMode: 'jd' });
  const a = autoById[p.id];
  const warns = p.issues.filter((i) => i.level !== 'info' || i.code === 'ARTIFACT' || i.code === 'CLAIM_MISMATCH');
  const notes = p.issues.filter((i) => i.code === 'REVIEW_NOTE');
  if (!p.corrections.length && !warns.length && !notes.length) continue;
  md += `\n### ${p.id} — ${p.headline || '(no headline)'}\nClassified **${r.classification.label}${r.classification.weak ? ' (weak)' : ''}** · LCA ${r.lca.score} · UI/UX ${r.uiux.score} · tenure ${(a.totalMonths / 12).toFixed(1)} → ${(p.totalMonths / 12).toFixed(1)} yrs (auto → reviewed)\n`;
  for (const c of p.corrections) md += `- **Correction** \`${c.field}\`: "${c.before}" → "${c.after}". ${c.reason}\n`;
  for (const n of notes) md += `- **Reviewer note**: ${n.message}\n`;
  for (const w of warns) md += `- *${w.level}* (${w.code}): ${w.message}\n`;
}
const nCorr = profiles.reduce((s, p) => s + p.corrections.length, 0);
md += `\n---\nTotals: ${nCorr} corrections on ${profiles.filter((p) => p.corrections.length).length} resumes; ${profiles.reduce((s, p) => s + p.issues.filter((i) => i.code === 'REVIEW_NOTE').length, 0)} reviewer notes; ${profiles.filter((p) => p.issues.some((i) => i.level === 'warning')).length} resumes with warnings; ${profiles.filter((p) => p.issues.some((i) => i.level === 'error')).length} unreadable.\n`;
fs.writeFileSync(path.join(ROOT, 'data/review/AUDIT_LOG.md'), md);
console.log('wrote data/review/AUDIT_LOG.md');
